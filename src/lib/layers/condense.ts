import type { DiffFile } from '../diff/parse-diff'
import type { Skeleton } from './build-skeleton'
import { buildMethodEdges, sharedIdentifiers } from './graph'
import { STEP_SIZE_LIMIT } from './layer-budget'
import type { FileRole } from './roles'

export interface PullRequestSummary {
	title: string
	body: string
}

export interface CondenseOptions {
	/** Characters the whole prompt may take. */
	budget?: number
	/** Characters of the pull request body kept in front of the file list. */
	bodyLimit?: number
}

/** The model reads the full list with its signals and a longer description. */
export const RICH_BUDGET = 40_000
export const RICH_BODY_LIMIT = 2_000
/** Diff excerpts for a hosted model: about 50k tokens, a cent on a cheap model, cached per revision. */
export const EXCERPT_BUDGET = 200_000

const SIGNAL_LENGTH = 60
// Never zero: a file with no signal is a path the model can only place by its directory.
const SIGNAL_LADDER = [6, 4, 2, 1]
const BOT_MARKERS = ['Summary by CodeRabbit', 'Reviewed by Cursor Bugbot', 'Generated by Copilot']

const SIGNAL_PATTERNS = [
	/export\s+(?:default\s+)?(?:async\s+)?(?:function|const|let|var|abstract\s+class|class|interface|type|enum)\s+(\w+)/,
	/^[\t ]*(?:abstract\s+)?(?:class|interface|type|enum)\s+(\w+)/,
	/\b(?:it|test|describe)(?:\.\w+)?\(\s*['"`]([^'"`\n]{3,})/,
	/@(?:Get|Post|Put|Patch|Delete|Controller)\(\s*['"`]([^'"`\n]*)/,
	/\b(?:path|route|url|href|to)\s*[:=]\s*['"`](\/[^'"`\n]*)/i,
	/\b(SELECT|INSERT INTO|UPDATE|DELETE FROM|CREATE TABLE|ALTER TABLE|DROP TABLE|CREATE INDEX)\b/,
]
// The function a hunk sits in, as git prints it: `export function useRepositorySearch(` or `class Foo {`.
const HUNK_CONTEXT = [
	/(?:function|const|let|var|class|interface|type|enum)\s+([\w$]+)/,
	/([\w$]+)\s*\(/,
]

const GUIDANCE_HEADING = 'Review guidance from the author'
// Headings and lead-ins authors use when they tell reviewers where to start.
const GUIDANCE_CUE =
	/(how to review|review(ing)? (order|guide|guidance|notes?|tips|hints|instructions|path|plan|strategy)|reviewer'?s? notes?|suggested (review )?order|where to start|start (the review |reviewing )?(with|from|at))/i
const GUIDANCE_LIMIT = 1500

/** The part of the description that tells reviewers how to read the change, if there is one. */
export function reviewGuidance(body: string): string {
	const lines = body.replace(/\r/g, '').split('\n')
	const start = lines.findIndex((line) => GUIDANCE_CUE.test(line))
	if (start < 0) return ''

	const heading = /^\s*#+\s|^\s*\*\*[^*]+\*\*\s*$/.test(lines[start] ?? '')
	const section: string[] = []
	for (const line of lines.slice(start)) {
		// A later heading ends the section; a bare cue sentence carries its own paragraph.
		if (section.length > 0 && (heading ? /^\s*#+\s|^\s*\*\*[^*]+\*\*\s*$/ : /^\s*$/).test(line))
			break
		section.push(line)
	}

	return section.join('\n').trim().slice(0, GUIDANCE_LIMIT)
}

export const guidanceBlock = (body: string) => {
	const guidance = reviewGuidance(body)

	return guidance
		? `${GUIDANCE_HEADING}, follow it for the steps and their order:\n${guidance}`
		: ''
}

export const groupingInstruction = (maxLayers: number) =>
	`Group the changed files of this pull request into review steps. A step is one behavior change: the definition or data shape it needs, the code that implements it, then its tests and docs. Steps span packages; directories, packages and file kinds are never steps. Every step gets an imperative title (max 6 words) that is true for every file in it and one sentence saying what to verify. Read shared data-shape changes first, new helpers before their callers, and keep a definition with its handler. The files array is the reading order. Use the signals after :: and the "needs @n" hints; do not invent dependencies on unchanged code. Every file appears exactly once. In each step, focus lists the files that deserve a careful read: new or changed logic, contracts and data shapes, migrations, auth, security, error handling, anything a reviewer would regret skimming. Leave out of focus what a glance settles: renames, moved code, mechanical import or call-site updates, generated files, styling, and tests of unchanged behavior. When the author's review guidance names steps or an order, those steps and that order win over the inferred hints. A step holds at most ${STEP_SIZE_LIMIT} files; a larger behavior becomes consecutive steps, each with its own title. Return between 1 and ${maxLayers} steps, one per independent behavior.`

function hunkContexts(file: DiffFile): string[] {
	const names: string[] = []
	for (const hunk of file.hunks) {
		const header = hunk.header.trim().slice(0, 200)
		if (!header) continue
		for (const pattern of HUNK_CONTEXT) {
			const name = pattern.exec(header)?.[1]
			if (name && name.length >= 3) {
				names.push(name)
				break
			}
		}
	}

	return names
}

function signalsFor(file: DiffFile, shared: string[], limit: number): string[] {
	const signals = new Set<string>()
	const add = (signal: string) => {
		if (signals.size < limit) signals.add(signal.slice(0, SIGNAL_LENGTH))
	}
	for (const identifier of shared) add(identifier)
	for (const name of hunkContexts(file)) add(name)
	const added = file.hunks.flatMap((hunk) => hunk.addedLines)
	for (const line of added) {
		if (signals.size >= limit) break

		for (const pattern of SIGNAL_PATTERNS) {
			const found = pattern.exec(line)?.[1]?.trim()
			if (!found) continue

			add(found)
			break
		}
	}
	// Docs, workflows and changelogs declare nothing: their first changed line says what they are about.
	if (signals.size === 0) {
		const first = [...added, ...file.hunks.flatMap((hunk) => hunk.removedLines)]
			.map((line) => line.trim())
			.find((line) => /\w{3,}/.test(line))
		if (first) add(first)
	}

	return [...signals]
}

export function cleanBody(body: string, limit: number): string {
	let text = body
	for (const marker of BOT_MARKERS) {
		const index = text.indexOf(marker)
		if (index >= 0) text = text.slice(0, index)
	}

	return text
		.replace(/[ \t]+\n/g, '\n')
		.replace(/\n{3,}/g, '\n\n')
		.trim()
		.slice(0, limit)
}

type FileLine = (path: string, role: FileRole, counts?: string) => string

function withinBudget(
	files: DiffFile[],
	pullRequest: PullRequestSummary,
	instruction: string,
	blocks: (line: FileLine) => string[],
	{ budget = RICH_BUDGET, bodyLimit = RICH_BODY_LIMIT }: CondenseOptions,
): string {
	const shared = sharedIdentifiers(files)
	const signals = new Map(
		files.map((file) => [
			file.path,
			signalsFor(file, shared.get(file.path) ?? [], SIGNAL_LADDER[0] ?? 1),
		]),
	)
	const title = `Pull request: ${pullRequest.title.trim() || '(untitled)'}`
	const body = cleanBody(pullRequest.body, bodyLimit)
	const guidance = guidanceBlock(pullRequest.body)

	// The guidance survives every cut but the last: it is worth more than the signals.
	const render = (limit: number, withBody: boolean) =>
		[
			withBody && body ? `${title}\n${body}` : title,
			...(guidance && (withBody || limit > 0) ? [guidance] : []),
			instruction,
			...blocks((path, role, counts = '') => {
				const shown = signals.get(path)?.slice(0, limit) ?? []

				return `- ${path} [${role}]${counts}${shown.length > 0 ? ` :: ${shown.join(' | ')}` : ''}`
			}),
		].join('\n\n')

	for (const limit of SIGNAL_LADDER) {
		const text = render(limit, true)
		if (text.length <= budget) return text
	}
	const withoutBody = render(1, false)
	if (withoutBody.length <= budget) return withoutBody

	// Paths only is the floor: every file must reach the model even when nothing else fits.
	return render(0, false)
}

export function condenseForGrouping(
	skeleton: Skeleton,
	files: DiffFile[],
	pullRequest: PullRequestSummary,
	options: CondenseOptions = {},
): string {
	const sizes = new Map(files.map((file) => [file.path, file]))
	const reviewable = skeleton.layers
		.flatMap((layer) => layer.files)
		.filter((file) => file.role !== 'generated')
		.sort((left, right) => left.path.localeCompare(right.path))

	const ids = new Map(reviewable.map((file, index) => [file.path, index + 1]))
	const dependencies = new Map<string, Set<number>>()
	for (const edge of [...skeleton.edges, ...buildMethodEdges(files)]) {
		const id = ids.get(edge.to)
		if (id !== undefined && ids.has(edge.from))
			dependencies.set(edge.from, (dependencies.get(edge.from) ?? new Set()).add(id))
	}
	const instruction = `${groupingInstruction(skeleton.maxLayers)} A file's @number identifies it; "needs @n" is a dependency inferred from this diff, so read @n before that file. In the answer, list files by their @number only (for example "@12"), never by path.`
	return withinBudget(
		files,
		pullRequest,
		instruction,
		(line) => [
			reviewable
				.map(({ path, role }) => {
					const file = sizes.get(path)
					const needs = [...(dependencies.get(path) ?? [])].map((id) => `@${id}`).join(',')

					return line(
						path,
						role,
						` +${file?.additions ?? 0}/-${file?.deletions ?? 0} @${ids.get(path)}${needs ? ` needs ${needs}` : ''}`,
					)
				})
				.join('\n'),
		],
		options,
	)
}

function renderHunks(file: DiffFile): string[] {
	return file.hunks.flatMap((hunk) => [
		`@@ ${hunk.header}`.trimEnd(),
		...(hunk.lines ?? [
			...hunk.removedLines.map((line) => `-${line}`),
			...hunk.addedLines.map((line) => `+${line}`),
		]),
	])
}

/**
 * The diff of every reviewable file, each cut to a fair share of the budget so a huge file
 * cannot crowd out the small ones that usually carry the behavior change.
 */
export function diffExcerpts(
	files: DiffFile[],
	skeleton: Skeleton,
	budget = EXCERPT_BUDGET,
): Map<string, string> {
	const reviewable = new Set(
		skeleton.layers
			.flatMap((layer) => layer.files)
			.filter((file) => file.role !== 'generated')
			.map((file) => file.path),
	)
	const rendered = files
		.filter((file) => reviewable.has(file.path) && !file.isBinary)
		.map((file) => ({ path: file.path, lines: renderHunks(file) }))
		.sort(
			(left, right) =>
				left.lines.join('\n').length - right.lines.join('\n').length ||
				left.path.localeCompare(right.path),
		)
	const excerpts = new Map<string, string>()
	let remaining = budget
	for (const [index, { path, lines }] of rendered.entries()) {
		const share = Math.floor(remaining / (rendered.length - index))
		const heading = `### ${path}`
		const marker = (shown: number) => `… ${lines.length - shown} more lines not shown`
		if (share < heading.length + marker(0).length + 2) continue
		const kept: string[] = []
		// Two for the blank line that separates this block from the previous one when joined.
		let used = heading.length + 2
		for (const line of lines) {
			if (used + line.length + 1 > share) break

			kept.push(line)
			used += line.length + 1
		}
		if (kept.length < lines.length) {
			while (kept.length > 0 && used + marker(kept.length).length + 1 > share)
				used -= (kept.pop()?.length ?? 0) + 1
			kept.push(marker(kept.length))
			used += (kept.at(-1)?.length ?? 0) + 1
		}
		remaining = Math.max(0, remaining - used)
		excerpts.set(path, [heading, ...kept].join('\n'))
	}

	return excerpts
}
